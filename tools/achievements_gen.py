"""Achievements: the C# table from docs/成就列表-*.md (Chinese) and tools/achievements_en.json (English), and the icon
atlas from the 3x3 icon sheets (output/achievement-icons/<first>-<last>.png, nine icons in the table's order) and
single redrawn icons named by their number (<id>.png), which replace the sheets' ones.

    python -I tools/achievements_gen.py [--preview path.png]

Writes src/TerraKnight/Achievements/AchievementDefs.cs and src/TerraKnight/Resources/AchievementIcons.png (16 icons a
row, 64x64 each, in the table's order; an icon not drawn yet is left clear and the game shows a question mark).
"""
import glob
import json
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = sorted(glob.glob(os.path.join(ROOT, 'docs', '成就列表-*.md')))[-1]
EN = os.path.join(ROOT, 'tools', 'achievements_en.json')
SHEETS = os.path.join(ROOT, 'output', 'achievement-icons')
OUT_CS = os.path.join(ROOT, 'src', 'TerraKnight', 'Achievements', 'AchievementDefs.cs')
OUT_PNG = os.path.join(ROOT, 'src', 'TerraKnight', 'Resources', 'AchievementIcons.png')

CATS = {'J': 'Journey', 'B': 'Boss', 'C': 'Challenge', 'I': 'Collect', 'E': 'Explore', 'G': 'Casino',
        'F': 'Fishing', 'H': 'Home', 'W': 'Combat', 'D': 'Death', 'X': 'Fun', 'M': 'Multi'}
ICON = 64
COLUMNS = 16


def read_doc():
    rows = []
    header = None
    for line in open(DOC, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line.startswith('|'):
            header = None if not line.strip() else header
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if cells[0] == '编号':
            header = cells
            continue
        if header is None or set(cells[0]) <= set('-'):
            continue
        if not re.fullmatch(r'[A-Z]\d\d', cells[0]):
            continue
        row = dict(zip(header, cells))
        rows.append({
            'id': cells[0],
            'zh': row['名称'],
            'cond': row['条件'],
            'stars': row['难度'].count('★'),
            'hidden': row.get('隐藏', '否') == '是',
        })
    return rows


def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write_defs(rows, en):
    lines = [
        '// Generated by tools/achievements_gen.py from docs/成就列表-*.md and tools/achievements_en.json: edit those, not this.',
        'namespace TerraKnight.Achievements',
        '{',
        '    internal static partial class AchievementDefs',
        '    {',
        '        public static readonly Def[] All =',
        '        {',
    ]
    for i, r in enumerate(rows):
        name, cond = en[r['id']]
        lines.append('            new Def({}, {}, Cat.{}, {}, {}, {}, {}, {}, {}),'.format(
            cs(r['id']), i, CATS[r['id'][0]], r['stars'], 'true' if r['hidden'] else 'false',
            cs(r['zh']), cs(r['cond']), cs(name), cs(cond)))
    lines += ['        };', '    }', '}', '']
    os.makedirs(os.path.dirname(OUT_CS), exist_ok=True)
    with open(OUT_CS, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(lines))
    print('defs', len(rows), '->', OUT_CS)


def runs(im, axis):
    """The cells along one axis: the long stretches between the sheet's near-black gutters."""
    w, h = im.size
    px = im.load()
    n, m = (w, h) if axis == 0 else (h, w)
    dark = []
    for i in range(n):
        c = 0
        for j in range(0, m, 4):
            r, g, b = px[i, j] if axis == 0 else px[j, i]
            if r + g + b < 40:
                c += 1
        dark.append(c / (m / 4) > 0.85)
    out, s = [], None
    for i, d in enumerate(dark + [True]):
        if not d and s is None:
            s = i
        if d and s is not None:
            if i - s > 50:
                out.append((s, i))
            s = None
    return out


def icon_of(cell):
    """A cell as a 64x64 pixel-art icon: the middle square, averaged down, its colours gathered."""
    w, h = cell.size
    side = min(w, h)
    cell = cell.crop(((w - side) // 2, (h - side) // 2, (w - side) // 2 + side, (h - side) // 2 + side))
    small = cell.resize((ICON, ICON), Image.BOX)
    return small.quantize(colors=48, method=Image.MEDIANCUT, dither=Image.NONE).convert('RGBA')


def write_atlas(rows, preview=None):
    order = [r['id'] for r in rows]
    index = {k: i for i, k in enumerate(order)}
    total = len(order)
    atlas = Image.new('RGBA', (COLUMNS * ICON, ((total + COLUMNS - 1) // COLUMNS) * ICON), (0, 0, 0, 0))
    have = set()
    for path in sorted(glob.glob(os.path.join(SHEETS, '*.png'))):
        m = re.fullmatch(r'([A-Z]\d\d)-([A-Z]\d\d)\.png', os.path.basename(path))
        if not m or m.group(1) not in index or m.group(2) not in index:
            print('skip', os.path.basename(path))
            continue
        ids = order[index[m.group(1)]:index[m.group(2)] + 1]
        im = Image.open(path).convert('RGB')
        cols, rws = runs(im, 0), runs(im, 1)
        if len(cols) != 3 or len(rws) != 3:
            print('bad grid', os.path.basename(path), cols, rws)
            continue
        for k, key in enumerate(ids[:9]):
            (x0, x1), (y0, y1) = cols[k % 3], rws[k // 3]
            icon = icon_of(im.crop((x0 + 3, y0 + 3, x1 - 3, y1 - 3)))
            i = index[key]
            atlas.paste(icon, ((i % COLUMNS) * ICON, (i // COLUMNS) * ICON))
            have.add(key)
    # Single icons named by their number (a redrawn one, "D27.png"): over whatever the sheets gave.
    for path in sorted(glob.glob(os.path.join(SHEETS, '*.png'))):
        key = os.path.splitext(os.path.basename(path))[0]
        if key not in index:
            continue
        im = Image.open(path).convert('RGB')
        icon = icon_of(im)
        i = index[key]
        atlas.paste(icon, ((i % COLUMNS) * ICON, (i // COLUMNS) * ICON))
        have.add(key)
        print('single', key)
    atlas.save(OUT_PNG, optimize=True)
    missing = [k for k in order if k not in have]
    print('icons', len(have), '/', total, '->', OUT_PNG)
    if missing:
        print('missing', missing[0], '...', missing[-1], len(missing))
    if preview:
        atlas.resize((atlas.width, atlas.height), Image.NEAREST).save(preview)


def main():
    rows = read_doc()
    en = json.load(open(EN, encoding='utf-8'))
    ids = [r['id'] for r in rows]
    assert len(ids) == len(set(ids)), 'duplicate ids'
    lost = [k for k in ids if k not in en]
    extra = [k for k in en if k not in ids]
    assert not lost and not extra, ('english', lost, extra)
    write_defs(rows, en)
    preview = sys.argv[sys.argv.index('--preview') + 1] if '--preview' in sys.argv else None
    write_atlas(rows, preview)


if __name__ == '__main__':
    main()
