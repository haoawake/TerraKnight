"""Generate the audited missing recipes from executed Terraria 1.4.5.8 data.

Keep the fixed target manifest: rerunning the audit must not erase the supplement.
Shop routes for otherwise unavailable materials are Hallownest adaptations.
"""
import itertools
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tools/vanilla-data/crafting'
read = lambda name: json.loads((DATA / name).read_text(encoding='utf-8-sig'))
vanilla, names = read('vanilla-runtime.json'), read('item-names.json')
targets = set(read('supplement-targets.json'))
types = {int(i):t for i,t in read('baseline-item-map.json').items()}
recipes = [r for r in vanilla['recipes'] if r['result'] in targets]
# Bone's platform round trip is sufficient; also retain the wall -> bone recipe.
needed = targets | {i for r in recipes for i, _ in r['ingredients']} | {1120, 2290, 2002}
# Dye Vat, common Bass and Worm support the newly usable rods.

extra = [i for i in sorted(needed) if i not in types]
for i in extra:
    types[i] = names[str(i)]['type']
cs = lambda s: json.dumps(s, ensure_ascii=False)
stage = lambda i: 4 if i in (4790, 6155, 5627, 5659, 5737, 5661) else 3 if i in (4881, 5064) else 0 if i in (2289,2291,2002,2290) else 1
out = ['// Generated by tools/generate_crafting_supplement.py; mechanics in ItemsCraftingSupplement.cs.',
       'using System.Collections.Generic;', 'namespace TerraKnight.Items { internal static partial class ItemDb {',
       'static void AddCraftingSupplement(List<ItemDef> list) {']
shop = []
crafted = {r['result'] for r in recipes} | {634}
for i in extra:
    t, d = types[i], vanilla['items'][str(i)]
    source = 'Craft' if i in crafted else 'Drop' if i == 2290 else 'Shop'
    out.append(f'list.Add(SupplementDef(ItemType.{t}, {cs(names[str(i)]["zh"])}, {i}, {d["rare"]}, {d["value"]}, {stage(i)}, ItemSource.{source}));')
    if source == 'Shop':
        # The dyes at the Dye Trader (Chest.SetupShop 12); the builder accessories are the Traveling Merchant's
        # (SetupTravelShop_GetItem), in TownNpcsMore's travelPool already.
        # The Angler's quest rewards (Player.GetAnglerReward) are his to give, not a shop's.
        npc = 'DyeTrader' if 'Dye' in t else 'PartyGirl' if 'Moss' in t or 'WingsInactive' in t else None if t in ('BrickLayer','ExtendoGrip','PaintSprayer','PortableCementMixer','HighTestFishingLine','AnglerEarring','TackleBox','FishingBobber') else 'Merchant'
        if npc: shop.append((npc,t,stage(i)))
out.extend(['}', '}', 'internal static partial class Recipes {', 'internal static Recipe[] SupplementRecipes() => new[] {'])
tiles = {-1:('徒手',0),18:('工作台',0),16:('砧',0),134:('秘银砧',4),114:('工匠作坊',1),125:('水晶球',4),228:('染缸',1),300:('骨头焊机',1)}
for r in recipes:
    station, s = tiles[r['tile']]
    choices=[]
    for i,n in r['ingredients']:
        ids={i}
        for g in r['groups']:
            accepted=vanilla['groups'][str(g)]
            if i in accepted: ids.update(x for x in accepted if x in types)
        choices.append([(j,n) for j in sorted(ids)])
    for ingredients in itertools.product(*choices):
        args=', '.join(f'(ItemType.{types[i]}, {n})' for i,n in ingredients)
        # Environmental conditions have an explicit Hallownest mapping, displayed in the guide.
        condition = ' { Environment = CraftEnvironment.Honey }' if 'needHoney' in r['conditions'] else ' { Environment = CraftEnvironment.Graveyard }' if 'needGraveyardBiome' in r['conditions'] else ''
        out.append(f'new Recipe(ItemType.{types[r["result"]]}, {r["count"]}, {cs(station)}, {s}, {args}){condition},')
out.append('new Recipe(ItemType.BoneBlockWall, 4, "骨头焊机", 1, (ItemType.Bone, 1)),')
out.append('new Recipe(ItemType.BonePlatform, 2, "徒手", 0, (ItemType.Bone, 1)),')
out.extend(['};', '}', '}'])
shopout = ['// Generated by tools/generate_crafting_supplement.py.', 'using TerraKnight.Items;', 'namespace TerraKnight.Town { internal static class CraftingSupplementShops {', 'internal static readonly (string Npc, ItemType Type, int Stage)[] All = {']
shopout.extend(f'({cs(npc)}, ItemType.{t}, {s}),' for npc,t,s in shop)
shopout.extend(['};', '}', '}'])
(ROOT/'src/TerraKnight/Town/CraftingSupplementShopsGenerated.cs').write_text('\n'.join(shopout)+'\n',encoding='utf8')
(ROOT/'src/TerraKnight/Items/RecipeSupplementGenerated.cs').write_text('\n'.join(out)+'\n',encoding='utf8')
(DATA/'supplement-shops.json').write_text(json.dumps(shop,ensure_ascii=False,indent=2),encoding='utf8')
# Append only: enum ordinals are persisted in saves and sent across the network.
file=ROOT/'src/TerraKnight/Items/Items.cs'; text=file.read_text('utf-8-sig')
end=text.index('\n    }',text.index('internal enum ItemType'))
missing=[types[i] for i in extra if not re.search(r'\b'+re.escape(types[i])+r'\b',text[:end])]
if missing:
    text=text[:end]+'\n        // Audited crafting supplement (append only).\n        '+', '.join(missing)+',\n'+text[end:]
    file.write_text(text,encoding='utf8')
print(f'{len(extra)} added definitions, {len(recipes)} original recipes, {len(shop)} ingredient shop routes')
