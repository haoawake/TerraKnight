"""Check all supported vanilla alternatives, not just one recipe per result."""
import argparse
import collections
import itertools
import json
import re
from pathlib import Path
from verify_vanilla_recipes import TILES, ROOT
from audit_crafting import expanded_ingredients


def coverage(runtime):
    vanilla = json.loads((ROOT/'tools/vanilla-data/crafting/vanilla-runtime.json').read_text('utf-8-sig'))
    names = json.loads((ROOT/'tools/vanilla-data/crafting/item-names.json').read_text('utf-8-sig'))
    items = runtime['items']
    if isinstance(items, list):
        items = {d['Type']: d for d in items}
    # Custom items can borrow a vanilla icon; they are not vanilla recipe results.
    ids = {t: int(m[1]) for t,d in items.items()
           if (m := re.fullmatch(r'Item_(\d+)', d.get('Texture') or ''))
           and names.get(m[1], {}).get('type') == t}
    types = {i:t for t,i in ids.items()}
    def key(result, count, tile, ingredients, environment):
        amounts = collections.Counter()
        for item, amount in ingredients:
            amounts[item] += amount
        return result, count, tile, tuple(sorted(amounts.items())), environment
    actual, results = set(), set()
    for r in runtime['recipes']:
        if r['Result'] in ids and all(i['Type'] in ids for i in r['Ingredients']):
            actual.add(key(ids[r['Result']], r['Count'], TILES.get(r['Station']),
                           [(ids[i['Type']], i['Count']) for i in r['Ingredients']], r.get('Environment','None')))
            results.add(ids[r['Result']])
    expected, unsupported, policy_excluded = set(), [], []
    flags = {'needWater':'Water','needLava':'Lava','needHoney':'Honey','needGraveyardBiome':'Graveyard'}
    for r in vanilla['recipes']:
        tile = 13 if r['tile'] == 355 else r['tile']
        # A registered item with no recipe at all is precisely the omission this
        # audit must catch; restricting to existing results hid whole wall chains.
        if r['result'] not in types:
            continue
        # These four native cross-fragment recipes would bypass this mod's
        # explicit one-pillar/one-fragment ownership progression.
        if types[r['result']] in {'FragmentSolar','FragmentVortex','FragmentNebula','FragmentStardust'}:
            policy_excluded.append(r)
            continue
        if tile not in TILES.values() or set(r['conditions']) - flags.keys():
            unsupported.append(r)
            continue
        choices = [[(i,n) for i in allowed if i in types] for allowed,n in expanded_ingredients(r,vanilla['groups'])]
        environment = next((e for flag,e in flags.items() if flag in r['conditions']), 'None')
        for ingredients in itertools.product(*choices):
            expected.add(key(r['result'],r['count'],tile,ingredients,environment))
    missing = sorted(expected-actual)
    def record(k):
        result,count,tile,ingredients,environment = k
        return dict(Result=types[result],Count=count,Tile=tile,Environment=environment,
                    Ingredients=[dict(Type=types[i],Count=n) for i,n in ingredients])
    return dict(ExpectedSupportedVariants=len(expected),Missing=[record(k) for k in missing],
                UnsupportedVanillaRecipes=unsupported,PolicyExcludedRecipes=policy_excluded,
                Scope='All implemented vanilla results and supported ingredients/stations/conditions; excludes cross-pillar fragment conversion to preserve boss ownership.')


if __name__ == '__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('runtime',type=Path)
    ap.add_argument('--output',type=Path,required=True)
    ap.add_argument('--generate',type=Path)
    args=ap.parse_args()
    report=coverage(json.loads(args.runtime.read_text('utf-8-sig')))
    args.output.write_text(json.dumps(report,ensure_ascii=False,indent=2),'utf-8')
    if args.generate:
        stations={v:k for k,v in TILES.items()}
        stations[-1]='徒手';stations[13]='玻璃瓶'
        lines=['// Generated by tools/RecipeAudit/recipe_variant_coverage.py from vanilla runtime data.',
               'using System.Collections.Generic;', 'namespace TerraKnight.Items { internal static partial class Recipes {',
               'static IEnumerable<Recipe> VanillaAlternativeRecipes() {']
        old = []
        if args.generate.exists():
            old = [line for line in args.generate.read_text('utf-8-sig').splitlines() if line.startswith('yield return ')]
        for r in report['Missing']:
            ingredients=', '.join(f'(ItemType.{i["Type"]}, {i["Count"]})' for i in r['Ingredients'])
            env='' if r['Environment']=='None' else ' { Environment=CraftEnvironment.'+r['Environment']+' }'
            lines.append(f'yield return new Recipe(ItemType.{r["Result"]}, {r["Count"]}, "{stations[r["Tile"]]}", 0, {ingredients}){env};')
        lines = lines[:4] + list(dict.fromkeys(old + lines[4:]))
        lines+=['}', '} }']
        args.generate.write_text('\n'.join(lines)+'\n','utf-8-sig')
    print(f'Supported variants={report["ExpectedSupportedVariants"]}; missing={len(report["Missing"])}; unsupported-condition/station records={len(report["UnsupportedVanillaRecipes"])}')
    if not args.generate:
        raise SystemExit(bool(report['Missing']))
