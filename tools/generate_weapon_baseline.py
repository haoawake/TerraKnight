"""Generate weapon damage references from the installed Terraria runtime dump.

Never infer original damage from the already balanced mod item export.
"""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--runtime', type=Path, default=root/'tools/vanilla-data/combat/vanilla-runtime.json')
p.add_argument('--output', type=Path, default=root/'src/TerraKnight/Items/VanillaWeaponDamage.cs')
a = p.parse_args()
data = json.loads(a.runtime.read_text(encoding='utf-8-sig'))
assert data['setupComplete'] and data['itemCount'] > 6000
assert 'useTime' in data['items']['1569'] and 'mana' in data['items']['1569'], 'Combat defaults must include original firing timing and mana'
rows = [(int(k), v) for k, v in data['items'].items() if v['damage'] > 0]
lines = ['// Generated by tools/generate_weapon_baseline.py from Terraria item defaults.',
         'using System.Collections.Generic;', 'namespace TerraKnight.Items', '{',
         '    internal static class VanillaWeaponDamage', '    {',
         '        internal static readonly Dictionary<int, (int Damage, int Rare, int UseTime, int Animation, int ReuseDelay, int Mana)> Values = new Dictionary<int, (int, int, int, int, int, int)>', '        {']
lines += [f'            [{k}] = ({v["damage"]}, {v["rare"]}, {v["useTime"]}, {v["useAnimation"]}, {v["reuseDelay"]}, {v["mana"]}),' for k, v in rows]
lines += ['        };', '    }', '}']
a.output.write_text('\n'.join(lines)+'\n', encoding='utf-8')
print(f'{len(rows)} original weapon/ammo/tool references -> {a.output}')
