"""Generate audit references from actual Terraria defaults and GrantArmorBenefits.

DumpArmor.cs invokes the installed assembly without starting a world. These
references are used by the isolated armour regression, never by item tuning.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root/'tools/vanilla-data/combat/vanilla-armor-bonuses.json').read_text(encoding='utf-8-sig'))
fields = {'statDefense':'Defense', 'statManaMax2':'ManaMax', 'maxMinions':'MaxMinions', 'maxTurrets':'MaxTurrets',
          'lifeRegen':'LifeRegen', 'meleeDamage':'MeleeDamage', 'rangedDamage':'RangedDamage', 'magicDamage':'MagicDamage',
          'minionDamage':'MinionDamage', 'meleeCrit':'MeleeCrit', 'rangedCrit':'RangedCrit', 'magicCrit':'MagicCrit',
          'meleeSpeed':'MeleeSpeed', 'moveSpeed':'MoveSpeed', 'manaCost':'ManaCost', 'pickSpeed':'PickSpeed',
          'endurance':'Endurance', 'whipRangeMultiplier':'WhipRange', 'arrowDamage':'ArrowMult',
          'bulletDamage':'BulletMult', 'rocketDamage':'SpecialistMult', 'aggro':'Aggro',
          'nightVision':'NightVision', 'noKnockback':'NoKnockback', 'fireWalk':'FireWalk'}
ints = {'Defense','ManaMax','MaxMinions','MaxTurrets','LifeRegen','Aggro'}

def props(row):
    result = []
    for original, mod in fields.items():
        value = row.get(original, 0)
        if not value:
            continue
        if original.endswith('Crit'):
            value /= 100
        if original == 'manaCost':
            value = -value
        rendered = 'true' if isinstance(value,bool) else str(int(value)) if mod in ints else f'{value:.5f}f'
        result.append(f'{mod} = {rendered}')
    ammo = .25 if row.get('ammoCost75') else .2 if (row.get('ammoCost80') or row.get('chloroAmmoCost80')) else .1 if row.get('huntressAmmoCost90') else 0
    if ammo:
        result.append(f'AmmoSave = {ammo}f')
    whip = row.get('whipUseTimeMultiplier', 0)
    if whip:
        result.append(f'WhipFaster = {1/(1+whip)-1:.5f}f')
    return 'new Bonuses { ' + ', '.join(result) + ' }'

lines = ['// Generated by tools/generate_armor_baseline.py from Terraria 1.4.5.8.',
         'using System.Collections.Generic;', 'namespace TerraKnight.Items', '{',
         '    internal static class VanillaArmorBonuses', '    {',
         '        internal static readonly Dictionary<int, Bonuses> Values = new Dictionary<int, Bonuses>', '        {']
lines += [f'            [{key}] = {props(row)},' for key,row in data['items'].items()]
lines += ['        };', '        internal static readonly Dictionary<ArmorSet, Bonuses> Sets = new Dictionary<ArmorSet, Bonuses>', '        {']
aliases = {'MetalTier1':['Copper','Tin','Iron'], 'MetalTier2':['Lead','Silver','Tungsten','Gold'],
           'Wood':['Wood','Ebonwood','RichMahogany','Pearlwood','Shadewood','BorealWood','PalmWood'],
           'ShadowScale':['Shadow'], 'ObsidianOutlaw':['Obsidian']}
for key,record in data['sets'].items():
    assert not record['error'] or key in ('Stardust','Forbidden'), (key,record['error'])
    for enum in aliases.get(key, [key.replace('Tier','T')]):
        lines.append(f'            [ArmorSet.{enum}] = {props(record["values"])},')
lines += ['        };', '    }', '}']
(root/'src/TerraKnight/Items/VanillaArmorBonuses.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'{len(data["items"])} original armour references and {len(data["sets"])} set callbacks')
