"""Compile the reviewed document's curated matrices into game-native data."""
from pathlib import Path
import importlib.util
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('plan', ROOT / 'tools/build_drop_balance_doc.py')
plan = importlib.util.module_from_spec(spec)
spec.loader.exec_module(plan)

def ids(ts):
    return ', '.join('ItemType.' + t for t in ts)

lines = ['// Generated by tools/generate_progression_balance.py from the reviewed drop plan.',
         'using System.Collections.Generic;', 'namespace TerraKnight.Items', '{',
         '    internal static partial class ProgressionBalance', '    {',
         '        internal static readonly ItemType[][][] Core = new ItemType[][][]', '        {']
for row in plan.CORE:
    lines.append('            new ItemType[][] { ' + ', '.join('new[] { ' + ids(ts) + ' }' for ts in row) + ' },')
lines += ['        };', '        internal static readonly ItemType[][][] AccessoryPaths = new ItemType[][][]', '        {']
for row in plan.ACCESSORIES:
    lines.append('            new ItemType[][] { ' + ', '.join('new[] { ' + ids(ts) + ' }' for ts in row) + ' },')
lines += ['        };', '        internal static readonly ArmorPath[] ArmorPaths = new ArmorPath[]', '        {']
for stage, cls, ts, *_ in plan.ARMOR_PATHS:
    lines.append(f'            new ArmorPath({stage}, Kit.{cls}, new[] {{ {ids(ts.split())} }}),')
lines += ['        };', '        internal static readonly Dictionary<string, BossReward> BossRewards = new Dictionary<string, BossReward>', '        {']
for key, stage, reason, ts, acc in plan.BOSSES:
    lines.append(f'            ["{key}"] = new BossReward({stage}, new[] {{ {ids(ts.split())} }}, ItemType.{acc}),')
lines += ['        };', '        internal static readonly Dictionary<ItemType, int> ResourceStages = new Dictionary<ItemType, int>', '        {']
stages = {t:s for ts,_,s,*_ in plan.MINERALS for t in ts.split()}
# The full reviewed acquisition policy supersedes the historical balance plan.
# Rates, quantities and regional preferences remain in the runtime loot tables.
policy = json.loads((ROOT / 'tools/resource_stage_policy.json').read_text('utf-8'))
for group in policy['groups'] + policy['stations']:
    for t in group['items'].split():
        stages[t] = group['stage']
# Ore and bar share the same processing gate.
import re
for m in re.finditer(r'new OreInfo\(ItemType\.(\w+), "[^"]+", \d+, ItemType\.(\w+)', plan.read('Items/ItemsOres.cs')):
    if m[1] in stages: stages[m[2]] = stages[m[1]]
for t,s in stages.items():
    lines.append(f'            [ItemType.{t}] = {s},')
lines += ['        };', '    }', '}']
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output',type=Path,default=ROOT/'src/TerraKnight/Items/ProgressionBalanceData.cs')
path=parser.parse_args().output
path.write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(path)
