"""Emit map positions and gate rows from the native Godhome terrain survey."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SURVEY = ROOT / 'artifacts/single-copy-godhomemap-20261018-013856/saves/godhome-map-survey.json'
data = json.loads(SURVEY.read_text(encoding='utf-8-sig'))
assert data['Failures'] == 0
rooms = {r['Scene']: r for r in data['Rooms']}
# Hubs form their own region. Independent statue/pantheon arenas are separate rooms,
# packed without pretending that dream warps are physical corridors.
fixed = {
    'GG_Atrium': (3600, 1200),
    'GG_Atrium_Roof': (3666, 1358),  # Native top1/bot1 meet exactly.
    'GG_Workshop': (4040, 1200),
    'GG_Blue_Room': (3600, 1040),
    'GG_Land_of_Storms': (4040, 1460),
    # These three GG-named rooms belong to Hallownest, not the dream realm.
    'GG_Pipeway': (1012, -1674),  # Waterways_08/left2 -> right1.
    'GG_Waterways': (682, -1784), # Pipeway/left1 -> right1.
    'GG_Lurker': (2896, -1075),  # Colosseum_Spectate/right1 -> left1.
}
x, y, height = 3600, 1800, 0
for name, room in sorted(rooms.items()):
    if name in fixed:
        room['X'], room['Y'] = fixed[name]
        continue
    if x + room['Width'] > 5600 and x > 3600:
        x, y, height = 3600, y + height + 60, 0
    room['X'], room['Y'] = x, y
    x += room['Width'] + 60
    height = max(height, room['Height'])
lines = ['// Generated by tools/generate-godhome-map.py from native scene geometry.',
         'using UnityEngine;', '', 'namespace TerraKnight.UI', '{',
         '    internal static partial class WorldMap', '    {', '        static WorldMap()', '        {']
for name, r in sorted(rooms.items()):
    lines.append(f'            layout["{name}"] = new Vector2Int({r["X"]}, {r["Y"]});')
labels = {'GG_Atrium': '神居中庭', 'GG_Atrium_Roof': '神居顶层', 'GG_Workshop': '众神堂',
          'GG_Blue_Room': '神居蓝色房间', 'GG_Land_of_Storms': '风暴之地',
          'GG_Spa': '神居温泉', 'GG_Waterways': '垃圾坑', 'GG_Pipeway': '垃圾坑通道', 'GG_Lurker': '苍白潜伏者'}
for name, label in labels.items():
    lines.append(f'            RoomNames["{name}"] = "{label}";')
lines += ['        }', '', '        static readonly string[] godhomeGateRows =', '        {']
for row in data['GateRows']:
    lines.append('            ' + json.dumps(row, ensure_ascii=False) + ',')
lines += ['        };', '    }', '}', '']
(ROOT / 'src/TerraKnight/UI/WorldMapGodhome.cs').write_text('\n'.join(lines), encoding='utf-8')
(ROOT / 'artifacts/godhome-map-placement.json').write_text(json.dumps(list(rooms.values()), ensure_ascii=False, indent=2), encoding='utf-8')
print(f'Generated {len(rooms)} native rooms and {len(data["GateRows"])} gate records')
