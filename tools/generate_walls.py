"""Generate wall items and recipes from Claude's preserved Terraria 1.4.5 survey."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tools/vanilla-data/hammer/walls-verified.json'
ITEMS = ROOT / 'src/TerraKnight/Items'


def main():
    walls = json.loads(DATA.read_text(encoding='utf-8'))
    source = (ITEMS / 'Items.cs').read_text(encoding='utf-8')
    # Append, preserving every existing enum value (network and save compatibility).
    source = re.sub(r'\n        // Generated wall items BEGIN.*?// Generated wall items END\n', '', source, flags=re.S)
    anchor = 'RelicWhiteDefender, RelicWingedNosk, RelicZote,'
    source = re.sub(re.escape(anchor) + r'\s*\n(?=    \})', anchor + '\n', source)
    enum = source[source.index('internal enum ItemType'):source.index('    internal enum', source.index('internal enum ItemType') + 1)]
    names = set(re.findall(r'\b[A-Za-z][A-Za-z0-9_]*\b', enum))
    added = [w['itemName'] for w in walls if w['itemName'] not in names]
    block = '\n        // Generated wall items BEGIN\n        ' + ', '.join(added) + ',\n        // Generated wall items END\n'
    assert source.count(anchor) == 1
    source = source.replace(anchor, anchor + block)
    if 'AddWalls(list);' not in source:
        source = source.replace('            AddRelics(list);', '            AddRelics(list);\n            AddWalls(list);')
    (ITEMS / 'Items.cs').write_text(source, encoding='utf-8')
    names.update(added)
    out = ['// Generated by tools/generate_walls.py; source: vanilla-data/hammer/walls-verified.json (runtime verified).',
           'using System.Collections.Generic;', 'namespace TerraKnight.Items {',
           'internal static partial class ItemDb {', 'static void AddWalls(List<ItemDef> list) {']
    for wall in walls:
        name = json.dumps(wall['zh'], ensure_ascii=False)
        out.append(f'list.Add(new ItemDef {{ Type = ItemType.{wall["itemName"]}, Name = {name}, Texture = "Item_{wall["item"]}", Source = ItemSource.Craft, PlacesWall = {wall["wall"]}, MaxStack = 9999, Consumable = true, UseTime = 7 * Tick, UseAnimation = 15 * Tick, Tooltip = "可放置背景墙\\n用锤子拆除", Value = {wall["value"]}, Rare = {wall["rare"]} }});')
    out += ['}', '}', 'internal static partial class Recipes {', 'static IEnumerable<Recipe> WallRecipes() {']
    recipes = set()
    count = 0
    stations = {'WorkBenches': '工作台', 'Furnaces': '熔炉', 'Anvils': '砧', 'MythrilAnvil': '秘银砧', 'CrystalBall': '水晶球', 'Loom': '织布机'}
    for wall in walls:
        for recipe in wall['recipes']:
            m = re.match(r'x(\d+) <- (.*?) @([A-Za-z0-9_]+)\(', recipe)
            if not m or m[3] not in stations:
                continue
            ingredients = re.findall(r'(\d+)×[^/]+/([^\[]+)\[(\d+)\]', m[2])
            if not ingredients:
                continue
            parts = []
            for n, en, itemid in ingredients:
                kind = en.replace(' ', '').replace("'", '').replace('-', '')
                if kind not in names:
                    break
                parts.append((kind, int(n)))
            else:
                key = (wall['itemName'], tuple(parts), m[3])
                if key in recipes:
                    continue
                recipes.add(key)
                station = json.dumps(stations[m[3]], ensure_ascii=False)
                stage = 4 if m[3] in ('MythrilAnvil', 'CrystalBall') else 0
                args = ', '.join(f'(ItemType.{kind}, {n})' for kind, n in parts)
                environment = ' { Environment = CraftEnvironment.Graveyard }' if wall['itemName'] == 'Cave8Echo' else ''
                out.append(f'yield return new Recipe(ItemType.{wall["itemName"]}, {m[1]}, {station}, {stage}, {args}){environment};')
                count += 1
                if len(parts) == 1 and parts[0][1] == 1:
                    out.append(f'yield return new Recipe(ItemType.{parts[0][0]}, 1, {station}, {stage}, (ItemType.{wall["itemName"]}, {m[1]}));')
                    count += 1
    out += ['}', '}', '}']
    (ITEMS / 'ItemsWallsGenerated.cs').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{len(walls)} walls, {count} recipes')


if __name__ == '__main__':
    main()
