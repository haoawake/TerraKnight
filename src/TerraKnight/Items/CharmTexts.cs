        /// <summary>The charm's description as it is now (Chinese).</summary>
        public static string Zh(int id, PlayerData pd)
        {
            if (id < 1 || id >= zh.Length) return "";
            if (pd != null)
            {
                if (id == 23 && pd.fragileHealth_unbreakable) return HeartWhole;
                if (id == 24 && pd.fragileGreed_unbreakable) return GreedWhole;
                if (id == 25 && pd.fragileStrength_unbreakable) return StrengthWhole;
                if (id == 36) return pd.royalCharmState >= 4 ? VoidHeart : pd.royalCharmState == 3 ? zh[36] : WhiteFragment;
                if (id == 40 && pd.grimmChildLevel >= 5) return CarefreeMelody;
            }
            return zh[id];
        }
